from pathlib import Path
import pandas as pd
import numpy as np

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    average_precision_score,
    brier_score_loss,
    confusion_matrix,
)


# ============================================================
# STEP 22
# LOCKED ENSEMBLE — FINAL TEST EVALUATION
# ============================================================

print("=" * 75)
print("STEP 22 — LOCKED ENSEMBLE FINAL TEST EVALUATION")
print("=" * 75)


# ------------------------------------------------------------
# 1. PATHS
# ------------------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parent

DATA_DIR = (
    PROJECT_ROOT
    / "data"
    / "processed"
)


# ------------------------------------------------------------
# 2. LOAD LOCKED CONFIGURATION
# ------------------------------------------------------------

config_file = (
    DATA_DIR
    / "locked_ensemble_configuration.csv"
)

config = pd.read_csv(config_file)

assert len(config) == 1

BEST_XGB_WEIGHT = float(
    config.loc[0, "xgb_weight"]
)

BEST_LGBM_WEIGHT = float(
    config.loc[0, "lgbm_weight"]
)

THRESHOLD = float(
    config.loc[0, "threshold"]
)

SEED = int(
    config.loc[0, "seed"]
)


print("\nLOCKED CONFIGURATION")
print("-" * 50)

print(
    f"XGBoost weight : {BEST_XGB_WEIGHT:.2f}"
)

print(
    f"LightGBM weight: {BEST_LGBM_WEIGHT:.2f}"
)

print(
    f"Classification threshold: {THRESHOLD:.2f}"
)

print(
    f"Seed: {SEED}"
)


# ------------------------------------------------------------
# 3. VERIFY WEIGHTS
# ------------------------------------------------------------

assert np.isclose(
    BEST_XGB_WEIGHT
    + BEST_LGBM_WEIGHT,
    1.0
)


# ------------------------------------------------------------
# 4. LOAD TEST PREDICTIONS
#
# These probabilities were generated by the already-trained
# seed-42 base models.
# ------------------------------------------------------------

test_file = (
    DATA_DIR
    / "base_models_test_predictions.csv"
)

test = pd.read_csv(test_file)


print("\nTest observations:", len(test))

assert len(test) == 110


# ------------------------------------------------------------
# 5. EXTRACT PREDICTIONS
# ------------------------------------------------------------

y_true = (
    test["y_true"]
    .astype(int)
    .to_numpy()
)

xgb_probability = (
    test["xgb_probability"]
    .to_numpy()
)

lgbm_probability = (
    test["lgbm_probability"]
    .to_numpy()
)


# ------------------------------------------------------------
# 6. CREATE LOCKED ENSEMBLE PROBABILITY
# ------------------------------------------------------------

ensemble_probability = (
    BEST_XGB_WEIGHT * xgb_probability
    + BEST_LGBM_WEIGHT * lgbm_probability
)


# ------------------------------------------------------------
# 7. CREATE FINAL TEST CLASSIFICATION
# ------------------------------------------------------------

ensemble_prediction = (
    ensemble_probability >= THRESHOLD
).astype(int)


# ------------------------------------------------------------
# 8. CALCULATE METRICS
# ------------------------------------------------------------

tn, fp, fn, tp = confusion_matrix(
    y_true,
    ensemble_prediction,
    labels=[0, 1]
).ravel()


accuracy = accuracy_score(
    y_true,
    ensemble_prediction
)

precision = precision_score(
    y_true,
    ensemble_prediction,
    zero_division=0
)

recall = recall_score(
    y_true,
    ensemble_prediction,
    zero_division=0
)

macro_f1 = f1_score(
    y_true,
    ensemble_prediction,
    average="macro",
    zero_division=0
)

auc_roc = roc_auc_score(
    y_true,
    ensemble_probability
)

auc_pr = average_precision_score(
    y_true,
    ensemble_probability
)

brier = brier_score_loss(
    y_true,
    ensemble_probability
)


# ------------------------------------------------------------
# 9. DISPLAY FINAL RESULTS
# ------------------------------------------------------------

print("\n" + "=" * 75)
print("FINAL LOCKED TEST RESULTS")
print("=" * 75)

print(
    f"Accuracy       : {accuracy:.6f}"
)

print(
    f"Precision      : {precision:.6f}"
)

print(
    f"Recall         : {recall:.6f}"
)

print(
    f"Macro-F1       : {macro_f1:.6f}"
)

print(
    f"AUC-ROC        : {auc_roc:.6f}"
)

print(
    f"AUC-PR         : {auc_pr:.6f}"
)

print(
    f"Brier score    : {brier:.6f}"
)

print("\nConfusion matrix components:")

print(
    f"TN = {tn}"
)

print(
    f"FP = {fp}"
)

print(
    f"FN = {fn}"
)

print(
    f"TP = {tp}"
)


# ------------------------------------------------------------
# 10. SAVE FINAL TEST PREDICTIONS
# ------------------------------------------------------------

final_predictions = pd.DataFrame(
    {
        "y_true": y_true,
        "xgb_probability": xgb_probability,
        "lgbm_probability": lgbm_probability,
        "ensemble_probability": ensemble_probability,
        "ensemble_prediction": ensemble_prediction,
    }
)

predictions_file = (
    DATA_DIR
    / "locked_ensemble_test_predictions.csv"
)

final_predictions.to_csv(
    predictions_file,
    index=False
)


# ------------------------------------------------------------
# 11. SAVE FINAL TEST METRICS
# ------------------------------------------------------------

metrics = pd.DataFrame(
    [
        {
            "model": "XGBoost-LightGBM Ensemble",
            "split": "test",
            "seed": SEED,
            "xgb_weight": BEST_XGB_WEIGHT,
            "lgbm_weight": BEST_LGBM_WEIGHT,
            "threshold": THRESHOLD,
            "accuracy": accuracy,
            "precision": precision,
            "recall": recall,
            "macro_f1": macro_f1,
            "auc_roc": auc_roc,
            "auc_pr": auc_pr,
            "brier_score": brier,
            "tn": tn,
            "fp": fp,
            "fn": fn,
            "tp": tp,
        }
    ]
)

metrics_file = (
    DATA_DIR
    / "locked_ensemble_test_results_seed42.csv"
)

metrics.to_csv(
    metrics_file,
    index=False
)


# ------------------------------------------------------------
# 12. FINAL VALIDATION
# ------------------------------------------------------------

assert len(final_predictions) == 110

assert np.isfinite(
    ensemble_probability
).all()

assert ensemble_prediction.shape == y_true.shape

assert (
    predictions_file.exists()
)

assert (
    metrics_file.exists()
)


print("\n" + "=" * 75)
print("STEP 22 COMPLETED SUCCESSFULLY")
print("=" * 75)

print("\nSaved:")
print(predictions_file)
print(metrics_file)

print("\n✓ Ensemble weight remained frozen")
print("✓ Test set used only for final evaluation")
print("✓ No test-based model selection performed")
print("✓ Final seed-42 test result recorded")

print("\nIMPORTANT:")
print("This is NOT yet the final thesis headline result.")
print("Ten-seed stability, comparator, ablation, and other required")
print("analyses still need to be completed.")